const DEFAULT_ROUTE = '/genlayer-rpc';
const DEFAULT_UPSTREAM = 'https://rpc-bradbury.genlayer.com';
const DEFAULT_MAX_BODY_BYTES = 1024 * 1024;
const DEFAULT_TIMEOUT_MS = 15_000;
const DEFAULT_MAX_BATCH_SIZE = 25;
const DEFAULT_RATE_LIMIT_REQUESTS = 240;
const DEFAULT_RATE_LIMIT_WINDOW_MS = 60_000;
const DEFAULT_MAX_RATE_LIMIT_CLIENTS = 4_096;
const DEFAULT_MAX_RESPONSE_BYTES = 5 * 1024 * 1024;
const DEFAULT_MAX_CONCURRENT_REQUESTS = 32;
const RAW_TRANSACTION_PROOF_MAX_RESPONSE_BYTES = 512 * 1024;
const TRANSACTION_HASH_PATTERN = /^0x[0-9a-fA-F]{64}$/;

const ALLOWED_GENLAYER_METHODS = new Set([
  'gen_call',
  'gen_getContractCode',
  'gen_getContractSchema',
  'gen_getContractState',
  'gen_getTransaction',
  'gen_getTransactionReceipt',
  'gen_getTransactionStatus',
  'gen_syncing',
]);

function isAllowedRpcMethod(method) {
  return typeof method === 'string'
    && (
      method.startsWith('eth_')
      || method === 'net_version'
      || method === 'web3_clientVersion'
      || ALLOWED_GENLAYER_METHODS.has(method)
    );
}

class RequestBodyError extends Error {
  constructor(statusCode, code, message) {
    super(message);
    this.name = 'RequestBodyError';
    this.statusCode = statusCode;
    this.code = code;
  }
}

function setCommonHeaders(res) {
  res.setHeader('access-control-allow-origin', '*');
  res.setHeader('access-control-allow-methods', 'POST, OPTIONS');
  res.setHeader('access-control-allow-headers', 'content-type');
  res.setHeader('access-control-max-age', '86400');
  res.setHeader('cache-control', 'no-store');
}

function json(res, statusCode, payload) {
  res.statusCode = statusCode;
  setCommonHeaders(res);
  res.setHeader('content-type', 'application/json; charset=utf-8');
  res.end(JSON.stringify(payload));
}

function rawJson(res, statusCode, payload) {
  res.statusCode = statusCode;
  setCommonHeaders(res);
  res.setHeader('content-type', 'application/json; charset=utf-8');
  res.end(payload);
}

function jsonRpcError(res, statusCode, code, message, id = null) {
  json(res, statusCode, {
    jsonrpc: '2.0',
    id,
    error: { code, message },
  });
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function isValidRequestId(id) {
  // JSON-RPC permits any finite JSON number. Only IDs generated by this
  // adapter need to be safe integers; caller-supplied numeric IDs stay intact.
  return id === null || typeof id === 'string' || (typeof id === 'number' && Number.isFinite(id));
}

function validateRequest(request) {
  if (!isPlainObject(request)) return false;
  if (request.jsonrpc !== '2.0' || typeof request.method !== 'string' || request.method.length === 0) {
    return false;
  }
  if (Object.hasOwn(request, 'id') && !isValidRequestId(request.id)) return false;
  if (
    Object.hasOwn(request, 'params')
    && !Array.isArray(request.params)
    && !isPlainObject(request.params)
  ) {
    return false;
  }
  return true;
}

function nextAvailableId(usedIds, candidate) {
  let next = candidate;
  while (usedIds.has(next)) {
    next += 1;
    if (!Number.isSafeInteger(next)) next = Number.MIN_SAFE_INTEGER;
  }
  return next;
}

/**
 * GenLayer RPC endpoints accept numeric JSON-RPC IDs more consistently than
 * wallet-generated string IDs.
 * Replace only string IDs, avoiding every numeric ID already present in the
 * payload, and retain a per-request lookup for restoring the caller's IDs.
 */
export function normalizeJsonRpcIds(payload) {
  const requests = Array.isArray(payload) ? payload : [payload];
  if (requests.length === 0 || !requests.every(validateRequest)) {
    throw new RequestBodyError(400, -32600, 'Invalid JSON-RPC 2.0 request.');
  }

  const usedIds = new Set(
    requests
      .filter((request) => Object.hasOwn(request, 'id') && typeof request.id === 'number')
      .map((request) => request.id),
  );
  const originalIds = new Map();
  let candidate = 1;

  const normalizedRequests = requests.map((request) => {
    if (!Object.hasOwn(request, 'id') || typeof request.id !== 'string') return request;

    candidate = nextAvailableId(usedIds, candidate);
    const normalizedId = candidate;
    usedIds.add(normalizedId);
    originalIds.set(normalizedId, request.id);
    candidate = normalizedId + 1;

    return { ...request, id: normalizedId };
  });

  return {
    payload: Array.isArray(payload) ? normalizedRequests : normalizedRequests[0],
    originalIds,
    expectsResponse: requests.some((request) => Object.hasOwn(request, 'id')),
  };
}

export function restoreJsonRpcIds(payload, originalIds) {
  const responses = Array.isArray(payload) ? payload : [payload];
  const restored = responses.map((response) => {
    if (!isPlainObject(response) || !originalIds.has(response.id)) return response;
    return { ...response, id: originalIds.get(response.id) };
  });
  return Array.isArray(payload) ? restored : restored[0];
}

function readBody(req, maxBodyBytes) {
  const declaredLength = Number(req.headers?.['content-length']);
  if (Number.isFinite(declaredLength) && declaredLength > maxBodyBytes) {
    req.resume?.();
    return Promise.reject(new RequestBodyError(413, -32000, 'JSON-RPC request body is too large.'));
  }

  return new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0;
    let settled = false;

    const fail = (error) => {
      if (settled) return;
      settled = true;
      reject(error);
    };

    req.on('data', (chunk) => {
      if (settled) return;
      const buffer = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
      size += buffer.length;
      if (size > maxBodyBytes) {
        fail(new RequestBodyError(413, -32000, 'JSON-RPC request body is too large.'));
        req.resume?.();
        return;
      }
      chunks.push(buffer);
    });
    req.on('end', () => {
      if (settled) return;
      settled = true;
      resolve(Buffer.concat(chunks).toString('utf8'));
    });
    req.on('aborted', () => fail(new RequestBodyError(400, -32700, 'JSON-RPC request was aborted.')));
    req.on('error', () => fail(new RequestBodyError(400, -32700, 'Unable to read JSON-RPC request body.')));
  });
}

function parseBody(body) {
  if (!body.trim()) throw new RequestBodyError(400, -32700, 'JSON-RPC request body is empty.');
  try {
    return JSON.parse(body);
  } catch {
    throw new RequestBodyError(400, -32700, 'JSON-RPC request body is not valid JSON.');
  }
}

function isValidResponsePayload(payload) {
  if (Array.isArray(payload)) return payload.length > 0 && payload.every(isPlainObject);
  return isPlainObject(payload);
}

async function readUpstreamBody(response, maxResponseBytes, abortController) {
  const declaredLength = Number(response?.headers?.get?.('content-length'));
  if (Number.isFinite(declaredLength) && declaredLength > maxResponseBytes) {
    abortController?.abort();
    throw new RequestBodyError(502, -32000, 'GenLayer JSON-RPC response is too large.');
  }

  if (!response?.body) return { bytes: Buffer.alloc(0), text: '' };
  if (typeof response.body.getReader !== 'function') {
    abortController?.abort();
    throw new RequestBodyError(502, -32000, 'GenLayer returned an unreadable JSON-RPC response body.');
  }

  const reader = response.body.getReader();
  const chunks = [];
  let total = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!(value instanceof Uint8Array)) {
        abortController?.abort();
        await reader.cancel().catch(() => {});
        throw new RequestBodyError(502, -32000, 'GenLayer returned a malformed JSON-RPC byte stream.');
      }
      total += value.byteLength;
      if (total > maxResponseBytes) {
        abortController?.abort();
        await reader.cancel().catch(() => {});
        throw new RequestBodyError(502, -32000, 'GenLayer JSON-RPC response is too large.');
      }
      chunks.push(Buffer.from(value));
    }
  } finally {
    reader.releaseLock?.();
  }

  const bytes = Buffer.concat(chunks, total);
  try {
    return {
      bytes,
      text: new TextDecoder('utf-8', { fatal: true }).decode(bytes),
    };
  } catch {
    abortController?.abort();
    throw new RequestBodyError(502, -32000, 'GenLayer returned an invalid UTF-8 JSON-RPC response.');
  }
}

/**
 * Same-origin JSON-RPC compatibility middleware for the configured GenLayer RPC.
 * The upstream URL is configuration-only, so this route cannot be used as an
 * arbitrary HTTP relay.
 */
export function createGenLayerRpcProxyMiddleware({
  fetchImpl = globalThis.fetch,
  upstreamUrl = DEFAULT_UPSTREAM,
  route = DEFAULT_ROUTE,
  maxBodyBytes = DEFAULT_MAX_BODY_BYTES,
  timeoutMs = DEFAULT_TIMEOUT_MS,
  maxBatchSize = DEFAULT_MAX_BATCH_SIZE,
  rateLimitRequests = DEFAULT_RATE_LIMIT_REQUESTS,
  rateLimitWindowMs = DEFAULT_RATE_LIMIT_WINDOW_MS,
  maxRateLimitClients = DEFAULT_MAX_RATE_LIMIT_CLIENTS,
  maxResponseBytes = DEFAULT_MAX_RESPONSE_BYTES,
  maxConcurrentRequests = DEFAULT_MAX_CONCURRENT_REQUESTS,
  clientKey = (req) => req.socket?.remoteAddress || req.connection?.remoteAddress || 'unknown',
  now = Date.now,
} = {}) {
  if (typeof fetchImpl !== 'function') throw new TypeError('A fetch implementation is required.');
  if (!Number.isSafeInteger(maxBodyBytes) || maxBodyBytes <= 0) {
    throw new TypeError('maxBodyBytes must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(timeoutMs) || timeoutMs <= 0) {
    throw new TypeError('timeoutMs must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(maxBatchSize) || maxBatchSize <= 0) {
    throw new TypeError('maxBatchSize must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(rateLimitRequests) || rateLimitRequests <= 0) {
    throw new TypeError('rateLimitRequests must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(rateLimitWindowMs) || rateLimitWindowMs <= 0) {
    throw new TypeError('rateLimitWindowMs must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(maxRateLimitClients) || maxRateLimitClients <= 0) {
    throw new TypeError('maxRateLimitClients must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(maxResponseBytes) || maxResponseBytes <= 0) {
    throw new TypeError('maxResponseBytes must be a positive safe integer.');
  }
  if (!Number.isSafeInteger(maxConcurrentRequests) || maxConcurrentRequests <= 0) {
    throw new TypeError('maxConcurrentRequests must be a positive safe integer.');
  }
  if (typeof clientKey !== 'function') throw new TypeError('clientKey must be a function.');
  if (typeof now !== 'function') throw new TypeError('now must be a function.');

  const requestWindows = new Map();
  let activeUpstreamRequests = 0;

  function currentTimestamp() {
    const timestamp = Number(now());
    return Number.isFinite(timestamp) && timestamp >= 0 ? timestamp : Date.now();
  }

  function purgeExpiredRateLimitWindows(timestamp) {
    for (const [key, window] of requestWindows) {
      if (!Number.isFinite(window.resetAt) || timestamp >= window.resetAt) requestWindows.delete(key);
    }
  }

  function touchRateLimitWindow(key, window) {
    requestWindows.delete(key);
    requestWindows.set(key, window);
  }

  function consumeRateLimit(req, units) {
    const timestamp = currentTimestamp();
    purgeExpiredRateLimitWindows(timestamp);
    const key = String(clientKey(req) || 'unknown');
    let window = requestWindows.get(key);
    if (!window) {
      window = { count: 0, resetAt: timestamp + rateLimitWindowMs };
      requestWindows.set(key, window);
    } else {
      touchRateLimitWindow(key, window);
    }
    while (requestWindows.size > maxRateLimitClients) {
      requestWindows.delete(requestWindows.keys().next().value);
    }
    if (window.count + units > rateLimitRequests) {
      return Math.max(1, Math.ceil((window.resetAt - timestamp) / 1000));
    }
    window.count += units;
    return null;
  }

  const genLayerRpcProxy = async function genLayerRpcProxy(req, res, next) {
    const requestUrl = new URL(req.url || '/', 'http://localhost');
    if (requestUrl.pathname !== route) return next();

    if (req.method === 'OPTIONS') {
      res.statusCode = 204;
      setCommonHeaders(res);
      res.end();
      return;
    }
    if (req.method !== 'POST') {
      res.setHeader('allow', 'POST, OPTIONS');
      jsonRpcError(res, 405, -32600, 'Only POST requests are allowed.');
      return;
    }

    let normalized;
    let rawTransactionProof = false;
    try {
      const requestPayload = parseBody(await readBody(req, maxBodyBytes));
      normalized = normalizeJsonRpcIds(requestPayload);
      const requests = Array.isArray(normalized.payload) ? normalized.payload : [normalized.payload];
      if (requests.length > maxBatchSize) {
        throw new RequestBodyError(413, -32000, `JSON-RPC batches are limited to ${maxBatchSize} calls.`);
      }
      if (!requests.every((request) => isAllowedRpcMethod(request.method))) {
        throw new RequestBodyError(403, -32601, 'JSON-RPC method is not allowed by this adapter.');
      }
      const [singleRequest] = requests;
      rawTransactionProof = !Array.isArray(normalized.payload)
        && Number.isSafeInteger(singleRequest.id)
        && singleRequest.method === 'eth_getTransactionByHash'
        && Array.isArray(singleRequest.params)
        && singleRequest.params.length === 1
        && TRANSACTION_HASH_PATTERN.test(String(singleRequest.params[0] || ''))
        && normalized.originalIds.size === 0;
      const retryAfter = consumeRateLimit(req, requests.length);
      if (retryAfter !== null) {
        res.setHeader('retry-after', String(retryAfter));
        throw new RequestBodyError(429, -32005, 'JSON-RPC rate limit exceeded.');
      }
    } catch (error) {
      if (error instanceof RequestBodyError) {
        jsonRpcError(res, error.statusCode, error.code, error.message);
        return;
      }
      jsonRpcError(res, 400, -32600, 'Invalid JSON-RPC 2.0 request.');
      return;
    }

    if (activeUpstreamRequests >= maxConcurrentRequests) {
      jsonRpcError(res, 503, -32005, 'GenLayer JSON-RPC adapter is at capacity.');
      return;
    }

    const abortController = new AbortController();
    const timeout = setTimeout(() => abortController.abort(), timeoutMs);
    activeUpstreamRequests += 1;
    try {
      const upstream = await fetchImpl(upstreamUrl, {
        method: 'POST',
        headers: {
          accept: 'application/json',
          'content-type': 'application/json',
        },
        body: JSON.stringify(normalized.payload),
        signal: abortController.signal,
      });

      // General RPC responses use the configured streaming cap. Raw transaction
      // proofs use a deliberately smaller bound because the browser must parse
      // the upstream bytes losslessly as security evidence.
      const responseLimit = rawTransactionProof
        ? Math.min(maxResponseBytes, RAW_TRANSACTION_PROOF_MAX_RESPONSE_BYTES)
        : maxResponseBytes;
      const upstreamBody = await readUpstreamBody(upstream, responseLimit, abortController);
      const responseBody = upstreamBody.text;
      if (!responseBody.trim()) {
        if (!normalized.expectsResponse && upstream.ok) {
          res.statusCode = 204;
          setCommonHeaders(res);
          res.end();
          return;
        }
        jsonRpcError(res, 502, -32000, 'GenLayer returned an empty JSON-RPC response.');
        return;
      }

      let responsePayload;
      try {
        responsePayload = JSON.parse(responseBody);
      } catch {
        jsonRpcError(res, 502, -32000, 'GenLayer returned an invalid JSON-RPC response.');
        return;
      }
      if (!isValidResponsePayload(responsePayload)) {
        jsonRpcError(res, 502, -32000, 'GenLayer returned a malformed JSON-RPC response.');
        return;
      }

      if (rawTransactionProof) {
        const requestId = normalized.payload.id;
        const hasResult = !Array.isArray(responsePayload)
          && Object.hasOwn(responsePayload, 'result');
        const hasError = !Array.isArray(responsePayload)
          && Object.hasOwn(responsePayload, 'error');
        if (
          Array.isArray(responsePayload)
          || responsePayload.jsonrpc !== '2.0'
          || responsePayload.id !== requestId
          || hasResult === hasError
          || (hasResult && responsePayload.result !== null && !isPlainObject(responsePayload.result))
          || (hasError && !isPlainObject(responsePayload.error))
        ) {
          jsonRpcError(res, 502, -32000, 'GenLayer returned a malformed transaction proof response.');
          return;
        }
        // Do not stringify this response. GenLayer transaction values are JSON
        // integer literals that can exceed Number.MAX_SAFE_INTEGER. Returning
        // the already size-bounded, structurally validated upstream bytes lets
        // the browser's strict proof parser preserve every integer digit.
        rawJson(res, upstream.status, upstreamBody.bytes);
        return;
      }

      json(
        res,
        upstream.status,
        restoreJsonRpcIds(responsePayload, normalized.originalIds),
      );
    } catch (error) {
      if (error instanceof RequestBodyError) {
        jsonRpcError(res, error.statusCode, error.code, error.message);
        return;
      }
      const message = error?.name === 'AbortError'
        ? 'GenLayer JSON-RPC request timed out.'
        : 'Unable to reach the configured GenLayer JSON-RPC endpoint.';
      jsonRpcError(res, 502, -32000, message);
    } finally {
      clearTimeout(timeout);
      activeUpstreamRequests -= 1;
    }
  };

  Object.defineProperty(genLayerRpcProxy, 'getDiagnostics', {
    enumerable: false,
    value: () => Object.freeze({
      activeUpstreamRequests,
      rateLimitClients: requestWindows.size,
    }),
  });
  return genLayerRpcProxy;
}

export function genLayerRpcProxyPlugin(options) {
  const middleware = createGenLayerRpcProxyMiddleware(options);
  const install = (server) => {
    server.middlewares.use(middleware);
  };
  return {
    name: 'liquidity-arena-genlayer-rpc-proxy',
    configureServer: install,
    configurePreviewServer: install,
  };
}

